import {cleanup,fireEvent,render,screen,waitFor} from "@testing-library/react";
import {afterEach,expect,it,vi} from "vitest";
import {SidecarHeader} from "./SidecarHeader";
import {NativeSidecar} from "./NativeSidecar";
import {sendSidecarMessage} from "./host";
vi.mock("./SidecarProject",()=>({SidecarProject:(props:{zh:boolean;onToggleLanguage:()=>void})=><><SidecarHeader zh={props.zh} onToggleLanguage={props.onToggleLanguage} showBrand={false}/><output data-testid="panel-props">{JSON.stringify(props)}</output></>}));
afterEach(()=>{cleanup();localStorage.removeItem("atlas-locale");vi.unstubAllGlobals();});
it("follows only its own window, keeps search available on other platforms and binds supported insertions",async()=>{
 const query=vi.fn().mockResolvedValue([{id:42,windowId:7,active:true,url:"https://chatgpt.com/c/current",title:"Current discussion"}]);
 const activated=vi.fn(),updated=vi.fn(),sendMessage=vi.fn().mockResolvedValue({ok:true});
 vi.stubGlobal("chrome",{windows:{getCurrent:async()=>({id:7})},tabs:{query,onActivated:{addListener:activated,removeListener:vi.fn()},onUpdated:{addListener:updated,removeListener:vi.fn()}},runtime:{sendMessage}});
 const view=render(<NativeSidecar zh/>);await waitFor(()=>expect(screen.getByTestId("panel-props")).toHaveTextContent('"conversationId":"current"'));
 expect(screen.getByTestId("panel-props")).toHaveTextContent('"canInsert":true');await sendSidecarMessage({type:"ATLAS_SIDECAR_HANDOFF",conversationId:"current",text:"reviewed"});expect(sendMessage).toHaveBeenLastCalledWith({type:"ATLAS_SIDECAR_HANDOFF",conversationId:"current",text:"reviewed",tabId:42});
 const onActivate=activated.mock.calls[0][0] as (info:{windowId:number})=>void;onActivate({windowId:99});expect(query).toHaveBeenCalledOnce();
 query.mockResolvedValue([{id:43,windowId:7,active:true,url:"https://claude.ai/new",title:"Claude"}]);onActivate({windowId:7});
 await waitFor(()=>expect(screen.getByTestId("panel-props")).toHaveTextContent('"conversationTitle":"Claude"'));expect(screen.getByTestId("panel-props")).toHaveTextContent('"canInsert":true');
 const instance=screen.getByTestId("panel-props");
 query.mockResolvedValue([{id:44,windowId:7,active:true,url:"https://example.com",title:"Unrelated page"}]);onActivate({windowId:7});
 await waitFor(()=>expect(instance).toHaveTextContent('"conversationId":""'));
 expect(screen.getByTestId("panel-props")).toBe(instance);
 expect(instance).toHaveTextContent('"canInsert":false');expect(instance).not.toHaveTextContent("Unrelated page");
 await sendSidecarMessage({type:"ATLAS_OPEN"});expect(sendMessage).toHaveBeenLastCalledWith({type:"ATLAS_OPEN"});
 query.mockResolvedValue([{id:42,windowId:7,active:true,url:"https://chatgpt.com/c/current",title:"Current discussion"}]);onActivate({windowId:7});
 await waitFor(()=>expect(instance).toHaveTextContent('"conversationId":"current"'));
 expect(screen.getByTestId("panel-props")).toBe(instance);
 await sendSidecarMessage({type:"ATLAS_SIDECAR_HANDOFF",conversationId:"current",text:"reviewed again"});expect(sendMessage).toHaveBeenLastCalledWith(expect.objectContaining({tabId:42,text:"reviewed again"}));
 view.unmount();await sendSidecarMessage({type:"ATLAS_OPEN"});expect(sendMessage).toHaveBeenLastCalledWith({type:"ATLAS_OPEN"});
});
it("switches panel language beside settings and remembers the choice without remounting conversation state",async()=>{
 vi.stubGlobal("chrome",{windows:{getCurrent:async()=>({id:7})},tabs:{query:async()=>[],onActivated:{addListener:vi.fn(),removeListener:vi.fn()},onUpdated:{addListener:vi.fn(),removeListener:vi.fn()}},runtime:{sendMessage:vi.fn()}});
 const view=render(<NativeSidecar zh/>);
 fireEvent.click(screen.getByLabelText("侧栏设置"));
 fireEvent.click(screen.getByRole("button",{name:"Switch to English"}));
 expect(screen.getByRole("button",{name:"AI settings"})).toBeVisible();
 expect(screen.getByTestId("panel-props")).toHaveTextContent('"zh":false');
 expect(localStorage.getItem("atlas-locale")).toBe("en");
 expect(document.documentElement.lang).toBe("en");
 view.unmount();render(<NativeSidecar zh/>);
 expect(screen.getByTestId("panel-props")).toHaveTextContent('"zh":false');
 fireEvent.click(screen.getByLabelText("Sidebar settings"));
 fireEvent.click(screen.getByRole("button",{name:"切换为中文"}));
 expect(screen.getByRole("button",{name:"AI 设置"})).toBeVisible();
 expect(localStorage.getItem("atlas-locale")).toBe("zh-CN");
});
it("keeps a tab-specific instance on its own conversation when another tab becomes active",async()=>{
 const get=vi.fn().mockResolvedValue({id:42,windowId:7,active:true,url:"https://chatgpt.com/c/owned",title:"Owned discussion"});
 const query=vi.fn(),activated={addListener:vi.fn(),removeListener:vi.fn()},updated={addListener:vi.fn(),removeListener:vi.fn()},sendMessage=vi.fn().mockResolvedValue({ok:true});
 vi.stubGlobal("chrome",{tabs:{get,query,onActivated:activated,onUpdated:updated},runtime:{sendMessage}});
 render(<NativeSidecar zh={false} tabId={42}/>);
 await waitFor(()=>expect(screen.getByTestId("panel-props")).toHaveTextContent('"conversationId":"owned"'));
 activated.addListener.mock.calls[0][0]({tabId:43,windowId:7});
 updated.addListener.mock.calls[0][0](43,{url:"https://chatgpt.com/c/other"},{id:43,active:true,windowId:7});
 expect(get).toHaveBeenCalledExactlyOnceWith(42);expect(query).not.toHaveBeenCalled();
 expect(screen.getByTestId("panel-props")).toHaveTextContent('"conversationId":"owned"');
 await sendSidecarMessage({type:"ATLAS_SIDECAR_HANDOFF",conversationId:"owned",text:"reviewed"});expect(sendMessage).toHaveBeenLastCalledWith(expect.objectContaining({tabId:42,conversationId:"owned"}));
 get.mockResolvedValue({id:42,url:"https://example.com",title:"Unrelated page"});
 updated.addListener.mock.calls[0][0](42,{url:"https://example.com"},{id:42});
 await waitFor(()=>expect(screen.queryByTestId("panel-props")).toBeNull());
 await sendSidecarMessage({type:"ATLAS_OPEN"});expect(sendMessage).toHaveBeenLastCalledWith({type:"ATLAS_OPEN"});
 get.mockResolvedValue({id:42,url:"https://chatgpt.com/c/back",title:"Back to AI"});
 updated.addListener.mock.calls[0][0](42,{url:"https://chatgpt.com/c/back"},{id:42});
 await waitFor(()=>expect(screen.getByTestId("panel-props")).toHaveTextContent('"conversationId":"back"'));
});
